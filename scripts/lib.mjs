// Pure helpers for scripts/setup.mjs, kept apart from the command-running code so they can be tested.
import { randomBytes } from 'node:crypto';

export const validWorkerName = s => typeof s === 'string' && /^[a-z0-9][a-z0-9-]{0,62}$/.test(s);
export const validSubdomain = s => typeof s === 'string' && /^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/.test(s);

// A random, identity-free workers.dev subdomain. It appears in every tracking-pixel URL a
// recipient's mail client loads, so it should not carry a name.
export function suggestSubdomain() {
  const alphabet = 'abcdefghijklmnopqrstuvwxyz0123456789';
  return 'mt-' + [...randomBytes(6)].map(b => alphabet[b % alphabet.length]).join('');
}

export const generatePassword = (bytes = 18) => randomBytes(bytes).toString('base64url');

export const isNotLoggedIn = text => /not authenticated/i.test(text);

// The accounts table printed by `wrangler whoami`.
export function parseAccounts(text) {
  const accounts = [];
  for (const line of text.split('\n')) {
    const m = line.match(/│\s*(.+?)\s*│\s*([0-9a-f]{32})\s*│/);
    if (m) accounts.push({ name: m[1], id: m[2] });
  }
  return accounts;
}

export function parseKvId(text) {
  const m = text.match(/"id":\s*"([0-9a-f]{32})"/);
  return m ? m[1] : null;
}

export function parseWorkerUrl(text) {
  const m = text.match(/https:\/\/[a-z0-9-]+\.[a-z0-9-]+\.workers\.dev/);
  return m ? m[0] : null;
}

// The values go into a TOML file, so anything that could add a line is refused up front.
export function renderWranglerConfig({ name, accountId, kvId }) {
  if (!validWorkerName(name)) throw new Error(`Invalid worker name: ${name}`);
  if (!/^[0-9a-f]{32}$/.test(accountId)) throw new Error('Invalid account id');
  if (!/^[0-9a-f]{32}$/.test(kvId)) throw new Error('Invalid KV namespace id');
  return `# Generated by scripts/setup.mjs. Holds your account and namespace ids, so it is git-ignored.
name = "${name}"
main = "src/index.js"
compatibility_date = "2024-01-01"
account_id = "${accountId}"

[[kv_namespaces]]
binding = "TRACKER"
id = "${kvId}"

# Drains queued webhooks shortly after each open. Without it scheduled() never runs.
[triggers]
crons = ["* * * * *"]
`;
}
